import { createServer } from "node:http";
import express from "express";
import wisp from "wisp-server-node";
import { uvPath } from "@titaniumnetwork-dev/ultraviolet";
import { epoxyPath } from "@mercuryworkshop/epoxy-transport";
import { baremuxPath } from "@mercuryworkshop/bare-mux/node";
const app = express();
app.use(express.static(new URL("./public/", import.meta.url).pathname));
app.use("/uv/", express.static(uvPath));
app.use("/epoxy/", express.static(epoxyPath));
app.use("/baremux/", express.static(baremuxPath));
app.get("/health", (_req,res)=>res.json({ok:true,engine:"ultraviolet"}));
app.use((_req,res)=>res.status(404).send("Not found"));
const server = createServer();
server.on("request",(req,res)=>{res.setHeader("Cross-Origin-Opener-Policy","same-origin");res.setHeader("Cross-Origin-Embedder-Policy","require-corp");app(req,res)});
server.on("upgrade",(req,socket,head)=>{if(req.url.endsWith("/wisp/"))wisp.routeRequest(req,socket,head);else socket.end()});
server.listen(Number(process.env.PORT||8080),"0.0.0.0");
